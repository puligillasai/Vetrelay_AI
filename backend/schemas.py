"""VetRelay AI — unified public schemas for the /api/* endpoints.

These models are consumed by IBM watsonx Orchestrate via OpenAPI 3.0 and MCP.
All fields intentionally avoid storing PII beyond the session lifetime.
"""

from __future__ import annotations

from enum import StrEnum

from pydantic import BaseModel, Field

# ---------------------------------------------------------------------------
# Enumerations
# ---------------------------------------------------------------------------


class TriageLevel(StrEnum):
    CRITICAL_EMERGENCY = "CRITICAL_EMERGENCY"
    URGENT = "URGENT"
    ROUTINE = "ROUTINE"


# ---------------------------------------------------------------------------
# Input
# ---------------------------------------------------------------------------


class PetIntakeInput(BaseModel):
    """Intake payload supplied by the pet owner or front-desk staff."""

    owner_name: str = Field(
        ...,
        min_length=1,
        max_length=120,
        description="Owner's name — used only for appointment labelling, never stored.",
        examples=["Jane Smith"],
    )
    pet_name: str = Field(..., min_length=1, max_length=80, examples=["Buddy"])
    species: str = Field(
        ...,
        description="e.g. canine, feline, avian, reptile",
        examples=["canine"],
    )
    age_years: float | None = Field(None, ge=0, description="Approximate age in years")
    reported_symptoms: list[str] = Field(
        ...,
        min_length=1,
        description="Free-text symptom tokens supplied by the owner.",
        examples=[["vomiting", "trembling", "pale gums"]],
    )
    duration_hours: float | None = Field(
        None, ge=0, description="How long symptoms have been present"
    )
    suspected_toxicity: bool = Field(
        False,
        description="Owner believes the pet ingested a toxic substance.",
    )


# ---------------------------------------------------------------------------
# Triage output
# ---------------------------------------------------------------------------


class TriageResult(BaseModel):
    """Result of the Human-AI Boundary Manager triage evaluation."""

    is_emergency: bool = Field(
        ...,
        description=(
            "When True the UI MUST display a full-screen emergency alert "
            "and block all non-emergency booking flows."
        ),
    )
    triage_level: TriageLevel
    severity_score: int = Field(
        ...,
        ge=1,
        le=5,
        description=(
            "1 = most critical, 5 = routine. Maps to CRITICAL(1), URGENT(2-3), ROUTINE(4-5)."
        ),
    )
    soap_summary: str = Field(
        ...,
        description="Structured SOAP brief generated by the Cognitive Load Reducer.",
    )
    action_required: str = Field(
        ...,
        description="Plain-language instruction for the owner or front-desk staff.",
    )


# ---------------------------------------------------------------------------
# Booking output
# ---------------------------------------------------------------------------


class BookingResult(BaseModel):
    """Clinic assignment produced by the Invisible Coordinator."""

    clinic_name: str
    address: str
    scheduled_slot: str = Field(
        ...,
        description="ISO-8601 datetime string or 'IMMEDIATE WALK-IN' for emergencies.",
    )
    instructions: str = Field(
        ...,
        description="Owner-facing instructions, including what to bring and what to expect.",
    )
